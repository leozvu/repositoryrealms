export function normalizeAppLocale(value) {
  return APP_LOCALES.includes(String(value || '').toLowerCase()) ? String(value).toLowerCase() : 'vi';
}

export function translateUiCopy(value, locale = 'vi') {
  if (locale !== 'en' || typeof value !== 'string' || !value) return value;
  const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
  const core = match?.[2] || value;
  const translated = EN_UI_COPY[core] || translateDynamicUiCopy(core);
  return translated ? `${match?.[1] || ''}${translated}${match?.[3] || ''}` : value;
}

