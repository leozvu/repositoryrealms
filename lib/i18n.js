export function normalizeAppLocale(value) {
  return APP_LOCALES.includes(String(value || '').toLowerCase()) ? String(value).toLowerCase() : 'vi';
}

export function translateUiCopy(value, locale = 'vi') {
  if (locale !== 'en' || typeof value !== 'string' || !value) return value;
  const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
  const core = match?.[2] || value;
  const translated = EN_UI_COPY[core] || translateDynamicUiCopy(core);
  return translated ? `${match?.[1] || ''}${translated}${match?.[3] || ''}` : value;
}

function translateDynamicUiCopy(value) {
  const patterns = [
    [/^Chào mừng trở lại, (.+)$/, (_match, name) => `Welcome back, ${name}`],
    [/^Đã mở (.+)\.$/, (_match, destination) => `Opened ${translateDestination(destination)}.`],
    [/^(\d+) đồng đội$/, (_match, count) => `${count} ${count === '1' ? 'teammate' : 'teammates'}`],
    [/^(\d+) nhiệm vụ$/, (_match, count) => `${count} ${count === '1' ? 'Quest' : 'Quests'}`],
    [/^(\d+) người trong tầm thoại$/, (_match, count) => `${count} ${count === '1' ? 'person' : 'people'} within voice range`],
    [/^(\d+) đến hạn trong 7 ngày$/, (_match, count) => `${count} due within 7 days`],
    [/^(\d+) ngày có TimeLog$/, (_match, count) => `${count} ${count === '1' ? 'day' : 'days'} with TimeLog`],
    [/^(\d+) thành viên$/, (_match, count) => `${count} ${count === '1' ? 'member' : 'members'}`],
    [/^(\d+) người$/, (_match, count) => `${count} ${count === '1' ? 'person' : 'people'}`],
    [/^(\d+(?:[.,]\d+)?h) ước lượng$/, (_match, hours) => `${hours} estimated`],
    [/^(\d+) vật phẩm sở hữu$/, (_match, count) => `${count} owned ${count === '1' ? 'item' : 'items'}`],
    [/^(\d+) vật phẩm đã mở khóa$/, (_match, count) => `${count} unlocked ${count === '1' ? 'item' : 'items'}`],
    [/^(\d+) đang hoạt động$/, (_match, count) => `${count} active`],
    [/^(\d+) yêu cầu đang chờ hội đồng$/, (_match, count) => `${count} ${count === '1' ? 'request' : 'requests'} awaiting council`],
    [/^(\d+) yêu cầu đang chờ$/, (_match, count) => `${count} pending ${count === '1' ? 'request' : 'requests'}`],
    [/^(\d+)\/(\d+) Quest đang mở(?: · (\d+) quá hạn)?$/, (_match, open, total, overdue) => `${open}/${total} open Quests${overdue ? ` · ${overdue} overdue` : ''}`],
    [/^(.+) · Đã duyệt$/, (_match, date) => `${date} · Approved`],
    [/^Mở chiến dịch (.+)$/, (_match, record) => `Open campaign ${record}`],
    [/^Mở bản ghi (.+)$/, (_match, record) => `Open record ${record}`],
    [/^Tiến độ (.+)$/, (_match, record) => `Progress: ${record}`],
    [/^Conversation ERP đã được tạo: (.+)$/, (_match, id) => `ERP Conversation created: ${id}`],
    [/^Message record đã được lưu: (.+)$/, (_match, id) => `Message record saved: ${id}`],
    [/^Contact request đã được ghi nhận: (.+)\.$/, (_match, id) => `Contact request recorded: ${id}.`],
    [/^(.+) Không tự gửi lại nếu trạng thái chưa chắc chắn; hãy đồng bộ danh sách\.$/, (_match, error) => `${error} Do not resend automatically when the outcome is uncertain; synchronize the list first.`],
  ];
  for (const [pattern, render] of patterns) {
    const matched = value.match(pattern);
    if (matched) return render(...matched);
  }
  return null;
}

function translateDestination(value) {
  const [label, ...context] = value.split(' · ');
  const translated = EN_UI_COPY[label] || label;
  return context.length ? `${translated} · ${context.join(' · ')}` : translated;
}
