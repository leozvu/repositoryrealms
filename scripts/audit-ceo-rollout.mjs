import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputDirectory = path.join(root, 'qa', 'ceo-rollout');
const checkOnly = process.argv.includes('--check');
const read = (relative) => fs.readFileSync(path.join(root, relative), 'utf8');

const rollout = read('lib/ceo-rollout.js');
const admin = read('lib/ceo-rollout-admin.js');
const migration = read('prisma/migrations/20260722050000_add_ceo_rollout_control_plane/migration.sql');
const page = read('app/(app)/ceo-rollout/page.jsx');
const css = read('app/(app)/ceo-rollout/rollout.module.css');
const roadmap = read('docs/realms/CEO-PORTAL-FOUR-ENTITY-PLAN.md');
const ringOrder = ['local_staging', 'read_only', 'ceo_sso', 'messaging', 'commands'];
const evidenceKinds = ['backup', 'restore_test', 'canary', 'reconciliation', 'rollback'];
const adapterFiles = [
  'lib/ceo-unified-dashboard-admin.js',
  'lib/ceo-identity-admin.js',
  'lib/ceo-messaging-admin.js',
  'lib/ceo-federation-admin.js',
  'lib/ceo-command-gateway-admin.js',
];
const routeFiles = [
  'app/api/ceo/v1/rollout/route.js',
  'app/api/ceo/v1/rollout/evidence/route.js',
  'app/api/ceo/v1/rollout/[entityId]/transition/route.js',
];

const adapterChecks = adapterFiles.map((file) => ({ file, guarded: read(file).includes('assertCeoRolloutCapability') }));
const routeChecks = routeFiles.map((file) => ({ file, exists: fs.existsSync(path.join(root, file)), privateNoStore: read(file).includes('ceoRolloutJson') }));
const summary = {
  ringsPresent: ringOrder.filter((ring) => rollout.includes(`'${ring}'`)).length,
  evidenceKindsPresent: evidenceKinds.filter((kind) => rollout.includes(`'${kind}'`)).length,
  outboundAdaptersGuarded: adapterChecks.filter((item) => item.guarded).length,
  outboundAdapters: adapterChecks.length,
  routesPresent: routeChecks.filter((item) => item.exists && item.privateNoStore).length,
  routes: routeChecks.length,
  migrationAdditive: !/DROP TABLE|DROP COLUMN|TRUNCATE|DELETE FROM/i.test(migration),
  seededFailClosed: /'local_staging', 'hold'/.test(migration),
  portalOnlyTransition: admin.includes('targetBusinessDatabaseTouched: false') && admin.includes('deploymentTriggered: false') && !/prisma migrate|vercel deploy|child_process/i.test(admin),
  productionHold: rollout.includes('CEO_ROLLOUT_CEO0_DECISION') && rollout.includes('ceo_rollout_production_hold'),
  makerChecker: rollout.includes('maker_checker') && rollout.includes('ceo_rollout_independent_review_required') === false && admin.includes('ceo_rollout_independent_review_required'),
  egoliveFinanceLocal: rollout.includes('ceo_rollout_egolive_finance_local_only') && rollout.includes('finance_review'),
  responsiveAccessibleUi: page.includes('<label>') && page.includes('role="alert"') && css.includes('min-height: 44px') && css.includes('prefers-reduced-motion'),
  roadmapUpdated: roadmap.includes('CEO-9') && roadmap.includes('fail-closed rollout'),
};
const result = { phase: 'CEO-9', generatedBy: 'scripts/audit-ceo-rollout.mjs', summary, adapterChecks, routeChecks };
const json = `${JSON.stringify(result, null, 2)}\n`;
const markdown = `# CEO-9 pilot and rollout audit\n\n- Rollout rings: **${summary.ringsPresent}/5**\n- Baseline evidence kinds: **${summary.evidenceKindsPresent}/5**\n- Guarded outbound adapters: **${summary.outboundAdaptersGuarded}/${summary.outboundAdapters}**\n- Private rollout routes: **${summary.routesPresent}/${summary.routes}**\n- Additive, fail-closed migration: **${summary.migrationAdditive && summary.seededFailClosed ? 'yes' : 'no'}**\n- Portal-only transitions: **${summary.portalOnlyTransition ? 'yes' : 'no'}**\n- Production HOLD gate: **${summary.productionHold ? 'yes' : 'no'}**\n- Maker/checker gate: **${summary.makerChecker ? 'yes' : 'no'}**\n- Egolive finance local-only gate: **${summary.egoliveFinanceLocal ? 'yes' : 'no'}**\n- Responsive/accessibility checks: **${summary.responsiveAccessibleUi ? 'yes' : 'no'}**\n\nGenerated by \`scripts/audit-ceo-rollout.mjs\`. No migration, deployment or entity write is performed by this audit.\n`;
const artifacts = { 'ceo-rollout-audit.json': json, 'ceo-rollout-audit.md': markdown };
const failures = [];
if (summary.ringsPresent !== 5) failures.push('five ordered rings required');
if (summary.evidenceKindsPresent !== 5) failures.push('baseline evidence contract incomplete');
if (summary.outboundAdaptersGuarded !== summary.outboundAdapters) failures.push('outbound rollout gates incomplete');
if (summary.routesPresent !== summary.routes) failures.push('rollout routes incomplete');
for (const [key, value] of Object.entries(summary)) if (typeof value === 'boolean' && !value) failures.push(`${key} failed`);

if (checkOnly) {
  const stale = Object.entries(artifacts).filter(([name, content]) => !fs.existsSync(path.join(outputDirectory, name)) || fs.readFileSync(path.join(outputDirectory, name), 'utf8') !== content).map(([name]) => name);
  if (stale.length) failures.push(`stale artifacts: ${stale.join(', ')}`);
} else {
  fs.mkdirSync(outputDirectory, { recursive: true });
  for (const [name, content] of Object.entries(artifacts)) fs.writeFileSync(path.join(outputDirectory, name), content, 'utf8');
}

if (failures.length) {
  for (const failure of failures) console.error(`[CEO-9] ${failure}`);
  process.exitCode = 1;
} else {
  console.log('CEO-9 rollout gate passed: 5/5 rings, 5/5 baseline evidence kinds, 5/5 outbound adapters guarded, production remains fail-closed.');
}
